using System.Collections.Generic;
using UnityEngine;

/// <summary>MAP NATURE — forests + sakura for the 60 sq km map
/// (2026-11-09 22:59 direction: the map is NOT only city).
///
/// TREE SOURCES (checked on disk 2026-11-09 — no usable real sakura or
/// forest tree was downloaded, so nothing is faked from the wrong model):
///   * Poly Haven detailed-env trees-plants: quiver_tree_01/02 (desert
///     trees, 150-270k tris each — wrong look, far too heavy),
///     dead_tree_trunk_02, rocks, bushes. Jacaranda was skipped-too-big
///     (214 MB, 312k tris) and is NOT on disk. None of these are used.
///   * FORESTS use the Kenney NatureKit trees ALREADY in the project
///     (Assets/Resources/Models/Kenney/NatureKit/): tree_pineDefaultA,
///     tree_oak, tree_detailed — real low-poly tree models, 0 extra MB.
///   * SAKURA is procedural (MeshFactory.BuildTrunk + BuildCanopy
///     blossom clusters, pink Lit material): no real pink-blossom model
///     exists in any account-free source on disk, and a Kenney tree
///     tinted pink would read as a green tree painted pink. The
///     procedural sakura is a real modelled tree (trunk + 5 canopy
///     blobs), not a box, and its canopy colour follows the season.
///
/// PLACEMENT: positions come from nature_placement.json (generated by
/// compute_new_layout.py, seeded, building/road/touge avoiding — see
/// the layout doc). The JSON lives in Resources/MapData/ (copied in by
/// the single import pass). Y is sampled LIVE at runtime from the
/// built ground (dem / fill / mountains), so trees sit on the terrain
/// whatever the layout is. 581 trees: 430 green Kenney + 151 sakura.
///
/// PERFORMANCE (size budget): trees are COMBINED per zone per material
/// (one mesh per zone per material, ~15-20 draw calls for the whole
/// map, ~220k tris total) — never one GameObject per tree. Shared
/// meshes + shared materials throughout; the Kenney kit adds 0 MB
/// (already in the project) and the sakura adds 0 MB (flat Lit
/// materials, no textures).
///
/// SEASONS: sakura canopies are pink in spring (their bloom) and leaf
/// out green in summer, orange in autumn, bare brown in winter — like
/// real sakura. SeasonManager calls SetSakuraSeason on every season
/// change; FestivalManager's petal particles still fall over Ueno Park
/// in spring on top of this. Trees are parented under the loader's
/// streaming cell roots (zone centre cell), so they stream with the
/// district they stand in.</summary>
public static class MapNature
{
    /// <summary>One tree placement from nature_placement.json.
    /// (Public nested types: JsonUtility deserialises them reliably.)</summary>
    [System.Serializable]
    public class TreePlacement
    {
        public float x, z, scale, rot;
        public string type;
        public string zone;
    }

    [System.Serializable]
    public class NatureData
    {
        public TreePlacement[] trees;
    }

    /// <summary>Resources path of the placement file (no extension).</summary>
    public const string PlacementPath = "MapData/nature_placement";

    /// <summary>True after Build ran (even when it built nothing).</summary>
    public static bool IsBuilt { get; private set; }
    /// <summary>Trees actually placed (combined into zone meshes).</summary>
    public static int TreeCount { get; private set; }

    static Material sakuraCanopyMat;
    static Material sakuraTrunkMat;
    static Material greenCanopyMat;

    /// <summary>Build all forests + sakura from the placement JSON.
/// Call after ConnectiveTerrain.Build (ground colliders must exist
    /// for the Y sampling). Safe to call when the JSON is missing:
    /// logs a warning and builds nothing (no invented placements).</summary>
    public static void Build(PlateauMapLoader loader)
    {
        IsBuilt = true;
        TreeCount = 0;
        if (loader == null) return;
        TextAsset json = Resources.Load<TextAsset>(PlacementPath);
        if (json == null)
        {
            Debug.LogWarning("[MapNature] no " + PlacementPath
                + " in Resources — forests/sakura skipped (import the placement JSON with the map)");
            return;
        }
        NatureData data;
        try { data = JsonUtility.FromJson<NatureData>(json.text); }
        catch (System.Exception e)
        {
            Debug.LogWarning("[MapNature] placement JSON unparsable: " + e.Message);
            return;
        }
        if (data == null || data.trees == null || data.trees.Length == 0)
        {
            Debug.LogWarning("[MapNature] placement JSON has no trees");
            return;
        }

        // Group placements by zone (one combined mesh per zone per material).
        var byZone = new Dictionary<string, List<TreePlacement>>();
        foreach (TreePlacement t in data.trees)
        {
            if (t == null || string.IsNullOrEmpty(t.type)) continue;
            string zone = string.IsNullOrEmpty(t.zone) ? "Unzoned" : t.zone;
            List<TreePlacement> list;
            if (!byZone.TryGetValue(zone, out list)) { list = new List<TreePlacement>(); byZone[zone] = list; }
            list.Add(t);
        }

        int placed = 0;
        int noGround = 0;
        foreach (KeyValuePair<string, List<TreePlacement>> kv in byZone)
        {
            placed += BuildZone(kv.Key, kv.Value, loader, ref noGround);
        }
        TreeCount = placed;
        Debug.Log("[MapNature] forests + sakura built: " + placed + " trees in "
            + byZone.Count + " zones (" + (placed - noGround) + " on live ground, "
            + noGround + " on mountain-profile fallback)"
            + (sakuraCanopyMat != null ? " | sakura canopy: seasonal" : ""));
    }

    /// <summary>One zone: combine every tree into per-material meshes.
/// Returns the number of trees placed.</summary>
    static int BuildZone(string zone, List<TreePlacement> trees, PlateauMapLoader loader, ref int noGround)
    {
        // Buckets keyed by material: one combined mesh per material.
        var buckets = new Dictionary<Material, MeshBucket>();
        Vector3 centreSum = Vector3.zero;
        int centreCount = 0;
        foreach (TreePlacement t in trees)
        {
            float y;
            if (!PlateauMapLoader.TryGetGroundHeight(t.x, t.z, out y))
            {
                y = MapTerrain.MountainHeight(t.x, t.z);
                noGround++;
            }
            Vector3 pos = new Vector3(t.x, y, t.z);
            centreSum += pos;
            centreCount++;
            Matrix4x4 treeMatrix = Matrix4x4.TRS(pos,
                Quaternion.Euler(0f, t.rot, 0f), Vector3.one * Mathf.Max(0.1f, t.scale));
            if (t.type == "sakura")
                AddSakura(buckets, treeMatrix);
            else
                AddKenneyTree(buckets, t.type, treeMatrix);
        }
        if (buckets.Count == 0 || centreCount == 0) return 0;

        // Parent under the streaming cell root of the zone centre.
        Transform parent = null;
        Vector2Int cell = DistrictData.CellForPosition(centreSum / centreCount);
        GameObject cellRoot = loader.GetCellRoot(cell);
        if (cellRoot != null) parent = cellRoot.transform;
        if (parent == null)
        {
            var fallback = new GameObject("MapNature");
            parent = fallback.transform;
            parent.SetParent(loader.transform, false);
        }

        foreach (KeyValuePair<Material, MeshBucket> kv in buckets)
        {
            Mesh mesh = kv.Value.ToMesh("Nature_" + zone + "_" + kv.Key.name);
            if (mesh == null) continue;
            var go = new GameObject("Nature_" + zone + "_" + kv.Key.name);
            go.transform.SetParent(parent, false);
            go.isStatic = true;
            var mf = go.AddComponent<MeshFilter>();
            mf.sharedMesh = mesh;
            var mr = go.AddComponent<MeshRenderer>();
            mr.sharedMaterial = kv.Key;
        }
        return trees.Count;
    }

    /// <summary>Procedural sakura: trunk + 5 pink blossom canopy blobs.</summary>
    static void AddSakura(Dictionary<Material, MeshBucket> buckets, Matrix4x4 treeMatrix)
    {
        if (sakuraTrunkMat == null)
            sakuraTrunkMat = MeshFactory.Lit("SakuraTrunk", new Color(0.35f, 0.22f, 0.12f), 0f, 0.4f);
        if (sakuraCanopyMat == null)
        {
            sakuraCanopyMat = MeshFactory.Lit("SakuraCanopy", SakuraColor(SeasonManager.Season.Spring), 0f, 0.6f);
            // The season may already be past spring when the map loads.
            if (SeasonManager.Instance != null)
                sakuraCanopyMat.color = SakuraColor(SeasonManager.Instance.Current);
        }
        Mesh trunk = MeshFactory.BuildTrunk();
        Mesh canopy = MeshFactory.BuildCanopy();
        AddMesh(buckets, sakuraTrunkMat, trunk,
            treeMatrix * Matrix4x4.TRS(new Vector3(0f, 1.5f, 0f), Quaternion.identity, Vector3.one));
        // Blossom clusters: one crown + four around it + one top.
        Vector3[] blobs = new Vector3[]
        {
            new Vector3(0f, 3.4f, 0f),
            new Vector3(0.95f, 2.7f, 0.6f),
            new Vector3(-0.9f, 2.8f, 0.55f),
            new Vector3(0.5f, 2.7f, -0.95f),
            new Vector3(-0.55f, 2.8f, -0.9f),
            new Vector3(0f, 4.3f, 0f),
        };
        float[] blobScale = new float[] { 2.3f, 1.5f, 1.5f, 1.5f, 1.5f, 1.3f };
        for (int i = 0; i < blobs.Length; i++)
            AddMesh(buckets, sakuraCanopyMat, canopy,
                treeMatrix * Matrix4x4.TRS(blobs[i], Quaternion.identity, Vector3.one * blobScale[i]));
    }

    /// <summary>Kenney NatureKit tree (pine / oak / detailed). Falls
    /// back to a procedural green tree when the kit prefab is missing.</summary>
    static void AddKenneyTree(Dictionary<Material, MeshBucket> buckets, string type, Matrix4x4 treeMatrix)
    {
        string prefabName;
        switch (type)
        {
            case "oak": prefabName = "tree_oak"; break;
            case "detailed": prefabName = "tree_detailed"; break;
            default: prefabName = "tree_pineDefaultA"; break; // "pine"
        }
        GameObject prefab = Resources.Load<GameObject>("Models/Kenney/NatureKit/" + prefabName);
        if (prefab == null)
        {
            Debug.LogWarning("[MapNature] Kenney tree prefab missing: " + prefabName
                + " — using procedural green tree instead");
            AddProceduralGreen(buckets, treeMatrix);
            return;
        }
        // Read the prefab's meshes through a temp instance (robust
        // localToWorldMatrix on the hierarchy), then destroy it.
        GameObject inst = Object.Instantiate(prefab);
        inst.hideFlags = HideFlags.HideAndDontSave;
        var filters = inst.GetComponentsInChildren<MeshFilter>(true);
        foreach (MeshFilter f in filters)
        {
            if (f == null || f.sharedMesh == null) continue;
            var rend = f.GetComponent<Renderer>();
            Material[] mats = rend != null ? rend.sharedMaterials : null;
            Mesh mesh = f.sharedMesh;
            for (int s = 0; s < mesh.subMeshCount; s++)
            {
                Material m = (mats != null && s < mats.Length && mats[s] != null)
                    ? mats[s] : null;
                if (m == null) continue;
                AddMeshSub(buckets, m, mesh, s,
                    treeMatrix * f.transform.localToWorldMatrix);
            }
        }
        Object.DestroyImmediate(inst);
    }

    /// <summary>Procedural green tree (fallback when a Kenney prefab
    /// is missing): trunk + 3 canopy blobs.</summary>
    static void AddProceduralGreen(Dictionary<Material, MeshBucket> buckets, Matrix4x4 treeMatrix)
    {
        if (sakuraTrunkMat == null)
            sakuraTrunkMat = MeshFactory.Lit("SakuraTrunk", new Color(0.35f, 0.22f, 0.12f), 0f, 0.4f);
        if (greenCanopyMat == null)
            greenCanopyMat = MeshFactory.Lit("GreenCanopy", new Color(0.25f, 0.45f, 0.2f), 0f, 0.6f);
        Mesh trunk = MeshFactory.BuildTrunk();
        Mesh canopy = MeshFactory.BuildCanopy();
        AddMesh(buckets, sakuraTrunkMat, trunk,
            treeMatrix * Matrix4x4.TRS(new Vector3(0f, 1.5f, 0f), Quaternion.identity, Vector3.one));
        Vector3[] blobs = new Vector3[]
        {
            new Vector3(0f, 3.2f, 0f),
            new Vector3(0.8f, 2.5f, 0.5f),
            new Vector3(-0.7f, 2.6f, -0.6f),
        };
        float[] blobScale = new float[] { 2.0f, 1.4f, 1.4f };
        for (int i = 0; i < blobs.Length; i++)
            AddMesh(buckets, greenCanopyMat, canopy,
                treeMatrix * Matrix4x4.TRS(blobs[i], Quaternion.identity, Vector3.one * blobScale[i]));
    }

    /// <summary>Sakura canopy colour by season: pink bloom in spring,
    /// green leaves in summer, orange in autumn, bare brown in winter.</summary>
    public static Color SakuraColor(SeasonManager.Season season)
    {
        switch (season)
        {
            case SeasonManager.Season.Spring: return new Color(1f, 0.62f, 0.75f);
            case SeasonManager.Season.Autumn: return new Color(0.85f, 0.45f, 0.2f);
            case SeasonManager.Season.Winter: return new Color(0.5f, 0.35f, 0.3f);
            default: return new Color(0.35f, 0.55f, 0.25f); // Summer green
        }
    }

    /// <summary>Season hook (called by SeasonManager on every season
    /// change and on boot): recolour the shared sakura canopy material.</summary>
    public static void SetSakuraSeason(SeasonManager.Season season)
    {
        if (sakuraCanopyMat != null)
            sakuraCanopyMat.color = SakuraColor(season);
    }

    // ---- mesh combining ----

    class MeshBucket
    {
        public List<Vector3> verts = new List<Vector3>();
        public List<Vector3> normals = new List<Vector3>();
        public List<Vector2> uvs = new List<Vector2>();
        public List<int> tris = new List<int>();

        public Mesh ToMesh(string name)
        {
            if (verts.Count == 0 || tris.Count == 0) return null;
            var mesh = new Mesh();
            mesh.name = name;
            mesh.vertices = verts.ToArray();
            mesh.normals = normals.ToArray();
            mesh.uv = uvs.ToArray();
            mesh.triangles = tris.ToArray();
            mesh.RecalculateBounds();
            return mesh;
        }
    }

    static MeshBucket BucketFor(Dictionary<Material, MeshBucket> buckets, Material mat)
    {
        MeshBucket b;
        if (!buckets.TryGetValue(mat, out b)) { b = new MeshBucket(); buckets[mat] = b; }
        return b;
    }

    static void AddMesh(Dictionary<Material, MeshBucket> buckets, Material mat, Mesh mesh, Matrix4x4 matrix)
    {
        for (int s = 0; s < mesh.subMeshCount; s++)
            AddMeshSub(buckets, mat, mesh, s, matrix);
    }

    static void AddMeshSub(Dictionary<Material, MeshBucket> buckets, Material mat, Mesh mesh, int sub, Matrix4x4 matrix)
    {
        MeshBucket b = BucketFor(buckets, mat);
        int baseIdx = b.verts.Count;
        Vector3[] verts = mesh.vertices;
        Vector3[] normals = mesh.normals;
        Vector2[] uvs = mesh.uv;
        // Rotation part of the matrix (uniform scale: normals just rotate).
        Matrix4x4 rot = matrix;
        rot.m00 = matrix.m00; rot.m01 = matrix.m01; rot.m02 = matrix.m02;
        rot.m03 = 0f; rot.m10 = matrix.m10; rot.m11 = matrix.m11; rot.m12 = matrix.m12;
        rot.m13 = 0f; rot.m20 = matrix.m20; rot.m21 = matrix.m21; rot.m22 = matrix.m22;
        rot.m23 = 0f; rot.m30 = 0f; rot.m31 = 0f; rot.m32 = 0f; rot.m33 = 1f;
        for (int i = 0; i < verts.Length; i++)
        {
            b.verts.Add(matrix.MultiplyPoint3x4(verts[i]));
            Vector3 n = (normals != null && i < normals.Length) ? normals[i] : Vector3.up;
            b.normals.Add(rot.MultiplyVector(n).normalized);
            b.uvs.Add((uvs != null && i < uvs.Length) ? uvs[i] : Vector2.zero);
        }
        int[] tris = mesh.GetTriangles(sub);
        for (int i = 0; i < tris.Length; i++) b.tris.Add(baseIdx + tris[i]);
    }
}
